const topLevelRoutes: RouteObject[] = [
  // Public auth screens. `/auth/*` must render with no session at all (D3):
  // a `pending_approval` user is never issued one.
  {
    element: <AuthShell />,
    errorElement: <RouteErrorBoundary />,
    children: [
      {
        path: ROUTES.login,
        element: <RedirectIfAuthenticated />,
        children: [{ index: true, lazy: page(() => import('@/features/auth/pages/LoginPage')) }],
      },
      {
        path: ROUTES.authPending,
        lazy: namedPage(
          () => import('@/features/auth/pages/AccountStatusPages'),
          'PendingApprovalPage',
        ),
      },
      {
        path: ROUTES.authRejected,
        lazy: namedPage(() => import('@/features/auth/pages/AccountStatusPages'), 'RejectedPage'),
      },
      {
        path: ROUTES.authSuspended,
        lazy: namedPage(() => import('@/features/auth/pages/AccountStatusPages'), 'SuspendedPage'),
      },
    ],
  },

  // Everything else lives behind a session and inside the app chrome.
  {
    element: <RequireAuth />,
    errorElement: <RouteErrorBoundary />,
    children: [
      {
        element: <AppShell />,
        children: authenticatedRoutes,
      },
    ],
  },

  { path: '*', element: <NotFound /> },
];

/** `RootLayout` wraps everything so the API layer gets a client-side `navigate`. */
export const routes: RouteObject[] = [
  {
    element: <RootLayout />,
    errorElement: <RouteErrorBoundary />,
    // The initial route is always `lazy`, so the data router needs something to
    // render while the first chunk loads.
    hydrateFallbackElement: <LoadingScreen fullscreen />,
    children: topLevelRoutes,
  },
];

export function createAppRouter() {
  return createBrowserRouter(routes);
}
