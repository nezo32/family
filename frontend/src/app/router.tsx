/**
 * ============================================================================
 *                            THE ROUTE CONTRACT
 * ============================================================================
 *
 * Other agents plug feature screens into the table below. This list is the
 * agreement between the shell and every feature module — do not invent new
 * top-level paths without updating `docs/architecture/frontend.md` and
 * `src/shared/lib/routes.ts` in the same change.
 *
 * | Path                     | Owner module        | Guard                    |
 * |--------------------------|---------------------|--------------------------|
 * | `/`                      | features/today      | auth                     |
 * | `/tasks`                 | features/tasks      | auth + `task:read`       |
 * | `/calendar`              | features/calendar   | auth + `event:read`      |
 * | `/goals`                 | features/goals      | auth + `goal:read`       |
 * | `/shopping`              | features/shopping   | auth + `shopping:read`   |
 * | `/wall`                  | features/wall       | auth                     |
 * | `/family`                | features/family     | auth + `member:read`     |
 * | `/settings`              | features/settings   | auth                     |
 * | `/settings/profile`      | features/settings   | auth                     |
 * | `/settings/notifications`| features/settings   | auth + `notification:manage:own` |
 * | `/settings/accounts`     | features/settings   | auth + `identity:manage:own`     |
 * | `/admin/members`         | features/admin      | auth + `member:approve`  |
 * | `/login`                 | features/auth       | public (redirects if signed in) |
 * | `/auth/pending`          | features/auth       | public                   |
 * | `/auth/rejected`         | features/auth       | public                   |
 * | `/auth/suspended`        | features/auth       | public                   |
 * | anything else            | —                   | 404                      |
 *
 * ### Rules for feature agents
 *
 * 1. **Do not edit this file to add sub-routes inside your own feature.** Add a
 *    nested `<Routes>`/`<Outlet>` inside your page, or ask the shell owner to
 *    add a child entry here. Detail views are *paths under your section*
 *    (`/tasks/:taskId`), never new top-level segments.
 * 2. Every page module **default-exports** a component that takes no props.
 * 3. Pages are lazy: the import lives here, so nothing in your feature is in
 *    the initial bundle.
 * 4. Guards are declarative and permission based (D4) — never `role ===`.
 *    `RequirePermission` takes the *base* permission; `own`/`any` is resolved
 *    by `useCan()`.
 * 5. Your page renders **inside** `AppShell`: no app bar, no navigation, no
 *    outer padding of your own. Start with `<PageHeader>`.
 *
 * `createBrowserRouter` (a data router) is required: `AppShell` uses
 * `useNavigation()` for the pending-navigation state, and the `lazy` route
 * property below is a data-router API.
 */

/** Helper: a lazily-loaded page module with a default export. */
function page(load: () => Promise<{ default: React.ComponentType }>) {
  return async (): Promise<{ Component: React.ComponentType }> => ({
    Component: (await load()).default,
  });
}

/** Helper: a lazily-loaded page exported under a name. */
function namedPage<K extends string>(load: () => Promise<Record<K, React.ComponentType>>, key: K) {
  return async (): Promise<{ Component: React.ComponentType }> => ({
    Component: (await load())[key],
  });
}

